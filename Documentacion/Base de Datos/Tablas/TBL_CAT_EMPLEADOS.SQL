 --Tabla para carga de los empleados de la empresa J.A.V.R----
 
 CREATE TABLE "SAMGSDB"."TBL_CAT_EMPLEADOS" 
   (	"ID_CONS" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_EMPLEADO" VARCHAR2(10 BYTE), 
	"NOMBRE" VARCHAR2(100 BYTE), 
	"APATERNO" VARCHAR2(100 BYTE), 
	"APMATERNO" VARCHAR2(100 BYTE), 
	"EDEPTO" NUMBER(10,0), 
	"EAREA" NUMBER(10,0), 
	"DIRECCION" VARCHAR2(200 BYTE), 
	"TELEFONO" VARCHAR2(14 BYTE), 
	"CELULAR" VARCHAR2(16 BYTE), 
	"EMAIL" VARCHAR2(100 BYTE), 
	"FALTAE" TIMESTAMP (6) DEFAULT SYSDATE, 
	"CTA_USU_LOCAL" VARCHAR2(10 BYTE), 
	"CTA_USU_GLOBAL" VARCHAR2(10 BYTE), 
    CONSTRAINT "TBL_CAT_EMPLEADOS_PK" PRIMARY KEY ("ID_EMPLEADO"),
    CONSTRAINT fk_EAREA FOREIGN KEY (EAREA) REFERENCES TBL_CAT_AREA(Id_Area),
    CONSTRAINT fk_EDEPTO FOREIGN KEY (EDEPTO) REFERENCES TBL_CAT_DEPARTAMENTO(Id_Depto));
    
--CREACION DE SECUENCIA INCRMENTO 1---   
CREATE SEQUENCE INCREMEMP
START WITH 1
INCREMENT BY 1;

--TRIGEER PARA EL INCREMENENTO DE 1----

CREATE OR REPLACE TRIGGER TRGEMP
BEFORE INSERT ON TBL_CAT_EMPLEADOS
FOR EACH ROW
BEGIN 
    SELECT INCREMEMP.NEXTVAL INTO  :NEW.ID_CONS FROM DUAL;    
END;