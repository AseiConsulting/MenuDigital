----Tabla Catalogo Depto----
CREATE TABLE TBL_CAT_DEPARTAMENTO
(	Id_Depto NUMBER(10), 
	Descripcion VARCHAR2(200),
    Falta TIMESTAMP DEFAULT(SYSDATE) NOT NULL,
    CONSTRAINT TBL_DEPTO_PK PRIMARY KEY (Id_Depto));
    
  
 --CREACION DE SECUENCIA INCRMENTO 1---   
CREATE SEQUENCE INCREMDPTO
START WITH 1
INCREMENT BY 1;

--TRIGEER PARA EL INCREMENENTO DE 1----

CREATE OR REPLACE TRIGGER TRGDPTO
BEFORE INSERT ON TBL_CAT_DEPARTAMENTO
FOR EACH ROW
BEGIN 
    SELECT INCREMDPTO.NEXTVAL INTO  :NEW.Id_Depto FROM DUAL;    
END;
