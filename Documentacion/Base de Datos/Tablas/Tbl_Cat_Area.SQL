---Tabla Catalogo Area para el control de las Areas de la empresa J.A.V.R---

CREATE TABLE TBL_CAT_AREA
(	Id_Area NUMBER(10), 
	Descripcion VARCHAR2(200),
    Depto NUMBER(10), 
    Falta TIMESTAMP DEFAULT(SYSDATE) NOT NULL,
    CONSTRAINT tbl_Cat_Area_PK PRIMARY KEY (Id_Area),
    CONSTRAINT fk_Depto FOREIGN KEY (Depto) REFERENCES TBL_CAT_DEPARTAMENTO(Id_Depto));
        
 --CREACION DE SECUENCIA INCRMENTO 1---   
CREATE SEQUENCE INCREMAREA
START WITH 1
INCREMENT BY 1;

--TRIGEER PARA EL INCREMENENTO DE 1----

CREATE OR REPLACE TRIGGER TRGAREA
BEFORE INSERT ON TBL_CAT_AREA
FOR EACH ROW
BEGIN 
    SELECT INCREMAREA.NEXTVAL INTO  :NEW.Id_Area FROM DUAL;    
END;


